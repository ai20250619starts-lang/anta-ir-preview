				<p>In the more than thirty years since I founded ANTA, one belief has remained constant: brand is the most important asset ANTA Sports holds. </p>
                
<p>Building a brand takes time and patience. The truly great brands are the ones that never waver from their positioning, that keep pushing to innovate, and that keep creating value for consumers. Consumer recognition, in turn, becomes the engine of brand growth, and brand growth, sustained over time, becomes lasting value. </p>

<p>Consumers today are more discerning than ever, with more choices than ever before. Every day, they vote with their choices for the brands they trust. That’s why we stay consumer-centric, protecting what makes each brand distinctive, focusing on differentiated product value and refusing to trade away a brand’s future for short-term gain.</p>

<p>Our job at the Group isn’t to push every brand to grow as fast as possible at every stage. It’s to respect each brand’s own pace of development, invest consistently, manage with patience and give every brand the room it needs to grow in a healthy way. It’s only when every brand is growing healthily that the Group as a whole can grow in a way that’s sustainable, high-quality and built to last. </p>

<p>A sports brand draws its energy from the field of play. That’s where the best ideas for innovation come from and it’s where products are truly put to the test. We take inspiration from sport, prove it out in competition and turn what we learn into better products and better experiences, bringing the results of professional sports to everyday consumers and earning their trust over the long run. </p>

<p>This is why we keep investing in brand building, product innovation and technology R&D, while strengthening our operational capabilities and building out our multi-brand, global presence. We believe that if we keep creating value for consumers, brand value naturally follows. By continuing to build brand value, and lasting value follows in turn.</p>

<p>I’m convinced that if we stay true to consumers, build strong brands and manufacture great products, and let every brand grow in its own healthy way, ANTA Sports will create lasting value – growing together with our consumers, our partners and our Shareholders.</p>






